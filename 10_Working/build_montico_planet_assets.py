"""Build the lightweight source atlases for the unlisted Montico planet.

Run from any directory. The only network request downloads NASA's public lunar
elevation map; artwork is read from the existing website. No sources are edited.
"""
from pathlib import Path
from io import BytesIO
from urllib.request import urlopen
import json

import numpy as np
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[1]
NASA = 'https://svs.gsfc.nasa.gov/vis/a000000/a004700/a004720/ldem_4_uint.tif'
PAINTINGS = [
    ('assets/images/front-page-image.jpg', 'Opera della pagina iniziale', 'Homepage artwork'),
    ('assets/images/private-milano-1971.jpg', 'Milano (1971)', 'Milano (1971)'),
    ('assets/images/private-prima-composizione.jpg', 'Prima composizione spaziale', 'Prima composizione spaziale'),
    ('assets/images/private-teatrino-infinito.jpg', "Teatrino dell’infinito", "Teatrino dell’infinito"),
    ('assets/images/private-il-sogno.jpg', 'Il sogno', 'Il sogno'),
    ('assets/images/private-omaggio-a-burri.jpg', 'Omaggio a Burri', 'Omaggio a Burri'),
    ('assets/images/private-arlecchino.jpg', 'Arlecchino', 'Arlecchino'),
    ('assets/images/private-wounded-knee.jpg', 'Wounded Knee', 'Wounded Knee'),
    ('assets/images/private-centrale-elettrica.jpg', 'La centrale elettrica', 'La centrale elettrica'),
    ('assets/images/private-signore-delle-mosche.jpg', 'Il signore delle mosche', 'Il signore delle mosche'),
    ('assets/images/private-santorini.jpg', 'Santorini', 'Santorini'),
    ('assets/images/hi-deserto-rosso.jpg', 'Deserto rosso', 'Deserto rosso'),
    ('assets/images/hi-fabbriche.jpg', 'Fabbriche', 'Fabbriche'),
    ('assets/images/hi-paure-inventate.jpg', 'Paure inventate', 'Paure inventate'),
    ('assets/images/hi-mosul.jpg', 'Interno esterno da Mosul (Iraq)', 'Interno esterno da Mosul (Iraq)'),
    ('assets/images/hi-viaggio-diametro.jpg', 'Viaggio - Diametro 92', 'Viaggio - Diametro 92'),
]
ARCHIVE_IDS = [5, 11, 32, 43, 62, 64, 71, 72, 105, 146, 159, 182, 202, 246, 250, 312]
ARCHIVE = [
    (f'assets/archive/montico-paintings/full/gm-{n:04d}.webp',
     f'Immagine dell’archivio fotografico GM-{n:04d}',
     f'Photographic archive image GM-{n:04d}') for n in ARCHIVE_IDS
]
# Include the surreal-watercolour collection as well as the photographic archive.
for position, number in ((1, 15), (7, 11), (13, 31)):
    name = f'AS-{number:04d}'
    ARCHIVE[position] = (f'assets/archive/acquerelli-surrealisti/{name}.jpeg',
                         f'Acquerelli surrealisti, immagine {name}',
                         f'Surreal Watercolors, image {name}')

def atlas(sources, destination):
    result = Image.new('RGB', (2048, 2048))
    for index, (path, _, _) in enumerate(sources):
        with Image.open(ROOT / path) as source:
            tile = ImageOps.fit(ImageOps.exif_transpose(source).convert('RGB'), (512, 512),
                                method=Image.Resampling.LANCZOS)
        result.paste(tile, ((index % 4) * 512, (index // 4) * 512))
    result.save(ROOT / destination, 'JPEG', quality=88, optimize=True, subsampling=0)

def main():
    for path, _, _ in PAINTINGS + ARCHIVE:
        if not (ROOT / path).is_file():
            raise FileNotFoundError(path)
    atlas(PAINTINGS, 'assets/images/pianeta-dipinti.jpg')
    atlas(ARCHIVE, 'assets/images/pianeta-frammenti.jpg')
    with urlopen(NASA, timeout=45) as response:
        lunar = Image.open(BytesIO(response.read()))
        values = np.asarray(lunar, dtype=np.float32)
    low, high = np.percentile(values, (0.5, 99.5))
    scaled = np.uint8(np.clip((values - low) * (255 / (high - low)), 0, 255))
    Image.fromarray(scaled).resize((512, 256), Image.Resampling.LANCZOS).save(
        ROOT / 'assets/images/pianeta-rilievo-lunare.png', optimize=True)
    pairs = [[{'image': path, 'it': it, 'en': en} for path, it, en in group]
             for group in (PAINTINGS, ARCHIVE)]
    data = '// Source metadata for the two artwork atlases. Generated by build_montico_planet_assets.py.\n'
    data += 'window.MONTICO_PLANET_WORKS = ' + json.dumps(pairs, ensure_ascii=False, indent=2) + ';\n'
    (ROOT / 'assets/data/pianeta-works.js').write_text(data, encoding='utf-8', newline='\n')
    print(f'Created two 16-work atlases and a 512 x 256 lunar relief; source percentiles {low:.0f}, {high:.0f}.')

if __name__ == '__main__':
    main()
